function getLang() {
  try {
    const saved = localStorage.getItem('tidnote_lang');
    if (saved === 'ko' || saved === 'en') return saved;
  } catch (e) {}
  return (navigator.language || 'en').toLowerCase().startsWith('ko') ? 'ko' : 'en';
}

function setLang(lang) {
  if (lang !== 'ko' && lang !== 'en') return;
  try { localStorage.setItem('tidnote_lang', lang); } catch (e) {}
  document.documentElement.lang = lang;
}
// 날짜 표시 형식: 선택한 언어를 따른다
function dateLocale() {
  return getLang() === 'ko' ? 'ko-KR' : 'en-US';
}
function t(key, vars) {
  const lang = getLang();
  let text = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) {
    for (const k in vars) text = text.split('{' + k + '}').join(String(vars[k]));
  }
  return text;
}

function applyI18n() {
  document.documentElement.lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    el.textContent = t(el.dataset.i18n);
  });
  // 입력창 안내 문구(placeholder)는 data-i18n-placeholder 로 지정한다
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
    // 메타 설명(content)과 접근성 이름(aria-label)
  document.querySelectorAll('[data-i18n-content]').forEach(function (el) {
    el.setAttribute('content', t(el.dataset.i18nContent));
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(function (el) {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  });
}

